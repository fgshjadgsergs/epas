export function answerFor(question: string): string {
  for (const r of ANSWER_RULES) if (r.test.test(question)) return r.answer;
  return 'Расскажем подробнее — напишите в чат или позвоните, менеджер ответит в течение 5 минут.';
}

/** Превращает список вопросов в пары вопрос+ответ для блока FAQ и Schema.org. */
export function faqItems(rawQuestions: string[]) {
  // Заглушки «—» из SEO-таблицы — не вопросы.
  const questions = rawQuestions.filter((q) => q && q.trim() !== '—');
  return questions.map((q) => ({ question: q, answer: answerFor(q) }));
}
